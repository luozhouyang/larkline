    #[test]
    fn v1_tokens_are_bound_to_scope_chat_operator_and_action() {
        let auth = auth(&[(1, "s3cret", false)]);
        let token = auth
            .sign_at(&sign_input("nonce_abc", AGENT_CALLBACK_ACTION), NOW)
            .unwrap();

        let mut wrong_scope = expected(AGENT_CALLBACK_ACTION);
        wrong_scope.scope = "oc_2".into();
        assert_eq!(
            auth.verify_at(&token, &wrong_scope, NOW),
            Err(CallbackRejection::ContextMismatch)
        );

        let mut wrong_chat = expected(AGENT_CALLBACK_ACTION);
        wrong_chat.chat_id = "oc_2".into();
        assert_eq!(
            auth.verify_at(&token, &wrong_chat, NOW),
            Err(CallbackRejection::ContextMismatch)
        );

        let mut wrong_operator = expected(AGENT_CALLBACK_ACTION);
        wrong_operator.operator_open_id = "ou_stranger".into();
        assert_eq!(
            auth.verify_at(&token, &wrong_operator, NOW),
            Err(CallbackRejection::ContextMismatch)
        );

        assert_eq!(
            auth.verify_at(&token, &expected("stop"), NOW),
            Err(CallbackRejection::ContextMismatch)
        );

        // Optional run id / fingerprint are compared only when supplied.
        let mut pinned = expected(AGENT_CALLBACK_ACTION);
        pinned.run_id = Some("run_1".into());
        pinned.policy_fingerprint = Some("fp_1".into());
        assert!(auth.verify_at(&token, &pinned, NOW).is_ok());
        pinned.run_id = Some("run_2".into());
        assert_eq!(
            auth.verify_at(&token, &pinned, NOW),
            Err(CallbackRejection::ContextMismatch)
        );
    }

