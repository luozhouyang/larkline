    #[test]
    fn malformed_tokens_are_rejected() {
        let auth = auth(&[(1, "s3cret", false)]);
        for token in [
            "",
            "bridge_cb.v1",
            "bridge_cb.v1.abc",
            "bridge_cb.v2.abcd.efgh",
            "not_a_token",
            "bridge_cb.v1.!!!!.%%%%",
            "bridge_cb.v1..",
        ] {
            assert_eq!(
                auth.verify_at(token, &expected(AGENT_CALLBACK_ACTION), NOW),
                Err(CallbackRejection::Malformed),
                "token {token:?}"
            );
        }

        // Valid base64 but not a JSON object with the required fields.
        let junk = base64url_encode(b"{\"r\":\"run\"}");
        let token = format!("{CALLBACK_TOKEN_PREFIX}.{junk}.{}", "A".repeat(43));
        assert_eq!(
            auth.verify_at(&token, &expected(AGENT_CALLBACK_ACTION), NOW),
            Err(CallbackRejection::Malformed)
        );

        // Standard-base64 characters are outside the contract.
        assert!(base64url_decode("ab+/").is_none());
        assert!(base64url_decode("ab==").is_none());
    }

    #[test]
    fn base64url_roundtrips_and_is_canonical() {
        for length in 0..=32 {
            let bytes: Vec<u8> = (0..length).map(|value| value as u8 * 7 + 3).collect();
            let encoded = base64url_encode(&bytes);
            assert!(!encoded.contains('='), "{encoded}");
            assert_eq!(
                base64url_decode(&encoded).as_deref(),
                Some(bytes.as_slice())
            );
        }
        // 0x69 encodes as "aQ"; "ab" has non-zero leftover bits and is
        // non-canonical, so it must be rejected instead of silently decoding.
        assert_eq!(base64url_decode("aQ").unwrap(), vec![0x69]);
        assert!(base64url_decode("ab").is_none());
        assert!(base64url_decode("a").is_none());
    }

    #[test]
    fn profile_extra_keys_take_precedence_over_the_environment() {
        let mut subject = profile();
        subject
            .extra
            .insert("callback".to_string(), json!({ "secret": "from-extra" }));
        let auth = CallbackAuth::from_profile_with(&subject, |_| Some("from-env".into()))
            .expect("configured");
        assert_eq!(auth.keys.len(), 1);
        assert_eq!(auth.keys[0].secret, "from-extra");
        assert_eq!(auth.keys[0].version, 1);

        // `extra.callback.keys` wins over `extra.callback.secret`.
        subject.extra.insert(
            "callback".to_string(),
            json!({
                "secret": "ignored",
                "keys": [
                    { "version": 1, "secret": "old", "retired": true },
                    { "version": 3, "secret": "new" }
                ]
            }),
        );
        let auth = CallbackAuth::from_profile_with(&subject, |_| None).expect("configured");
        assert_eq!(auth.key_versions(), vec![1, 3]);
        assert!(auth.keys[0].retired);
        assert!(!auth.keys[1].retired);

        // Environment fallback, including the legacy variable name.
        let env_only = |name: &str| match name {
            CALLBACK_SECRET_ENV => None,
            LEGACY_CALLBACK_SECRET_ENV => Some("  from-env  ".to_string()),
            _ => None,
        };
        let auth = CallbackAuth::from_profile_with(&profile(), env_only).expect("configured");
        assert_eq!(auth.keys[0].secret, "from-env");
    }

