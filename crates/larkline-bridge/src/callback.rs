type HmacSha256 = Hmac<Sha256>;

/// Prefix of a version 1 callback token (same constant as the TypeScript
/// `PREFIX`).
pub const CALLBACK_TOKEN_PREFIX: &str = "bridge_cb.v1";

/// Action name bound into tokens for agent-rendered buttons. The TypeScript
/// dispatcher uses the same string (`'agent_callback'`).
pub const AGENT_CALLBACK_ACTION: &str = "agent_callback";

/// Marker key on a button value that flags the click as a bridge callback.
pub const BRIDGE_CALLBACK_MARKER: &str = "__bridge_cb";

/// Token field of an agent-rendered callback button.
pub const BRIDGE_TOKEN_FIELD: &str = "bridge_token";

/// Environment variable holding the version 1 callback key.
pub const CALLBACK_SECRET_ENV: &str = "LARKLINE_CALLBACK_SECRET";

/// Callback key honoured for compatibility with the TypeScript field name.
const LEGACY_CALLBACK_SECRET_ENV: &str = "LARK_CHANNEL_CALLBACK_SECRET";

/// TTL used by callers that want the TypeScript run-card lifetime (24h).
pub const DEFAULT_CALLBACK_TTL_MS: i64 = 24 * 60 * 60 * 1000;

// ---------------------------------------------------------------------------
// Bridge-rendered buttons (unchanged contract)
// ---------------------------------------------------------------------------

pub struct CallbackTokens {
    key: [u8; 32],
}

impl std::fmt::Debug for CallbackTokens {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("CallbackTokens").finish_non_exhaustive()
    }
}

impl Default for CallbackTokens {
    fn default() -> Self {
        Self::new()
    }
}

impl CallbackTokens {
    pub fn new() -> Self {
        let mut key = [0u8; 32];
        if getrandom::fill(&mut key).is_err() {
            // getrandom failing is unrecoverable for security; fall back to a
            // process-random key so buttons still cannot be forged offline.
            let mut seed = format!("{:?}{:?}", std::process::id(), std::time::SystemTime::now());
            for (index, byte) in key.iter_mut().enumerate() {
                *byte = seed.as_bytes().get(index).copied().unwrap_or(0)
                    ^ (std::time::SystemTime::now()
                        .duration_since(std::time::UNIX_EPOCH)
                        .map(|d| d.subsec_nanos() as u8)
                        .unwrap_or(0)
                        + index as u8);
            }
            seed.clear();
        }
        Self { key }
    }

    pub fn sign(&self, scope: &str, action: &str) -> String {
        let mut mac = HmacSha256::new_from_slice(&self.key).expect("hmac accepts any key length");
        mac.update(scope.as_bytes());
        mac.update(b"\0");
        mac.update(action.as_bytes());
        hex(&mac.finalize().into_bytes())
    }

    pub fn verify(&self, scope: &str, action: &str, token: &str) -> bool {
        let Some(provided) = unhex(token) else {
            return false;
        };
        let mut mac = HmacSha256::new_from_slice(&self.key).expect("hmac accepts any key length");
        mac.update(scope.as_bytes());
        mac.update(b"\0");
        mac.update(action.as_bytes());
        mac.verify_slice(&provided).is_ok()
    }
}

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

fn unhex(value: &str) -> Option<Vec<u8>> {
    if value.len() % 2 != 0 || value.len() != 64 {
        return None;
    }
    let mut out = Vec::with_capacity(32);
    for pair in value.as_bytes().chunks(2) {
        let text = std::str::from_utf8(pair).ok()?;
        out.push(u8::from_str_radix(text, 16).ok()?);
    }
    Some(out)
}

