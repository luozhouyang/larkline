//! Signed callback tokens for card buttons.
//!
//! Two independent contracts live here:
//!
//! 1. **Bridge-rendered buttons** ([`CallbackTokens`]) — the run card's stop
//!    button. The value carries `{ __bridge_cb: true, action, scope, token }`
//!    and the token is `hex(HMAC-SHA256(key, scope || 0x00 || action))` with a
//!    process-local random key. Buttons rendered before a restart simply stop
//!    verifying, which is the safe failure mode.
//!
//! 2. **Agent-rendered callbacks** ([`CallbackAuth`]) — a port of
//!    `src/card/callback-auth.ts`. A card button the agent sends through
//!    `lark-cli` carries `{ __bridge_cb: true, bridge_token: "<token>" }`; on
//!    click the bridge verifies the token and feeds the remaining payload back
//!    to the agent as a `[card-click] {…}` message in the same session.
//!
//! ## v1 token contract
//!
//! ```text
//! token   = "bridge_cb.v1." + b64url(payload_json) + "." + b64url(hmac)
//! payload = {"r":…,"s":…,"c":…,"o":…,"a":…,"exp":…,"fp":…,"n":…,"kv":…}
//! hmac    = HMAC-SHA256(secret_of_key_version_kv, b64url(payload_json))
//! b64url  = RFC 4648 base64url, no padding
//! exp     = expiry as Unix milliseconds
//! ```
//!
//! Fields (identical to the TypeScript implementation): `r` run id, `s` scope,
//! `c` chat id, `o` operator open id, `a` action, `exp` expiry, `fp` policy
//! fingerprint, `n` nonce, `kv` key version. The HMAC is taken over the
//! *encoded* payload string, exactly like the TypeScript `sign()`.
//!
//! To stay interoperable with a token minted by a bridge-aware `lark-cli`,
//! signing and verification must produce the same JSON bytes; the module tests
//! pin a token generated by the TypeScript implementation.
//!
//! ## Key configuration
//!
//! The TypeScript bridge signs with key version 1 = the profile's App Secret
//! (`src/bot/channel.ts`). The Rust `Bridge` is not handed that secret, so the
//! same algorithm runs with a key configured explicitly; the bridge and the
//! card-signing client must share the value. Sources, first one wins:
//!
//! 1. profile `extra.callback.keys`:
//!    `[{"version": 1, "secret": "…", "retired": false}]`
//! 2. profile `extra.callback.secret` (or `extra.callbackSecret`): version 1
//! 3. environment `LARKLINE_CALLBACK_SECRET`: version 1
//!
//! With no key configured nothing verifies: [`CallbackAuth::from_profile`]
//! returns `None`, the bridge fails closed and logs that agent callbacks are
//! disabled. Retired keys keep verifying old buttons but are never used to
//! sign.
//!
//! ## Verification
//!
//! [`CallbackAuth::verify`] checks the prefix, parses the payload, resolves
//! the key version, verifies the HMAC in constant time, enforces `exp`, checks
//! the expected context, and finally consumes the nonce, so a replayed token
//! is rejected. The caller supplies what it can bind via
//! [`CallbackExpected`]: scope, chat id, operator open id and action.
//! `run_id` and `policy_fingerprint` are optional because the Rust bridge
//! keeps neither TypeScript run ids nor policy fingerprints; it also has no
//! per-topic scopes yet, so `s` must equal the chat id.
//!
//! Replay protection is in-memory: a token replayed after a bridge restart is
//! accepted until it expires. The TypeScript implementation persists used
//! nonces in `callback-nonces.json`; the Rust bridge deliberately keeps the
//! verifier dependency-free (no file I/O in this module).

use std::collections::HashMap;
use std::fmt;
