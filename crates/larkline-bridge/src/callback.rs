/// One HMAC key. `version` is the `kv` payload field; `retired` keys verify
/// old buttons but are never chosen for signing.
#[derive(Clone)]
pub struct CallbackKey {
    pub version: u32,
    pub secret: String,
    pub retired: bool,
}

impl fmt::Debug for CallbackKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Never print secret material, not even at debug level.
        f.debug_struct("CallbackKey")
            .field("version", &self.version)
            .field("retired", &self.retired)
            .finish_non_exhaustive()
    }
}

/// Decoded version 1 payload. The short field names are the wire format.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CallbackPayload {
    /// Run id (`r`).
    pub r: String,
    /// Scope (`s`).
    pub s: String,
    /// Chat id (`c`).
    pub c: String,
    /// Operator open id (`o`).
    pub o: String,
    /// Action (`a`).
    pub a: String,
    /// Expiry, Unix milliseconds (`exp`).
    pub exp: i64,
    /// Policy fingerprint (`fp`).
    pub fp: String,
    /// Nonce (`n`).
    pub n: String,
    /// Key version (`kv`).
    pub kv: u32,
}

/// Context a token must be bound to. `None` fields are not compared because
/// the Rust bridge has no equivalent (see the module docs).
#[derive(Debug, Clone, Default)]
pub struct CallbackExpected {
    pub run_id: Option<String>,
    pub scope: String,
    pub chat_id: String,
    pub operator_open_id: String,
    pub action: String,
    pub policy_fingerprint: Option<String>,
}

/// Input for [`CallbackAuth::sign`].
#[derive(Debug, Clone, Default)]
pub struct CallbackSignInput {
    pub run_id: String,
    pub scope: String,
    pub chat_id: String,
    pub operator_open_id: String,
    pub action: String,
    pub policy_fingerprint: String,
    pub ttl_ms: i64,
    /// Fixed nonce for tests; a random one is generated when `None`.
    pub nonce: Option<String>,
}

/// Why a token was rejected. Kept small and non-secret so it can be logged.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CallbackRejection {
    Malformed,
    UnknownKey,
    BadSignature,
    Expired,
    ContextMismatch,
    Replay,
}

impl CallbackRejection {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Malformed => "malformed",
            Self::UnknownKey => "unknown-key",
            Self::BadSignature => "bad-signature",
            Self::Expired => "expired",
            Self::ContextMismatch => "context-mismatch",
            Self::Replay => "nonce-replay",
        }
    }
}

impl fmt::Display for CallbackRejection {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Version 1 callback signer/verifier.
#[derive(Debug)]
pub struct CallbackAuth {
    keys: Vec<CallbackKey>,
    /// nonce -> expiry (ms). Pruned on every verify so the map stays bounded
    /// by the tokens accepted within their TTL.
    nonces: Mutex<HashMap<String, i64>>,
}

impl CallbackAuth {
    /// Build a verifier from explicit keys. Returns `None` when no key carries
    /// a usable secret, which disables agent callbacks (fail closed).
    pub fn new(keys: Vec<CallbackKey>) -> Option<Self> {
        let mut seen = std::collections::HashSet::new();
        let mut keys: Vec<CallbackKey> = keys
            .into_iter()
            .filter(|key| !key.secret.trim().is_empty())
            .filter(|key| seen.insert(key.version))
            .collect();
        if keys.is_empty() {
            return None;
        }
        keys.sort_by_key(|key| key.version);
        Some(Self {
            keys,
            nonces: Mutex::new(HashMap::new()),
        })
    }

    /// Build a verifier from the profile's `extra` map, then the environment.
    pub fn from_profile(profile: &ProfileConfig) -> Option<Self> {
        Self::from_profile_with(profile, |name| std::env::var(name).ok())
    }

    /// [`CallbackAuth::from_profile`] with an injectable environment, so the
    /// key-source precedence is testable without mutating process env.
    pub(crate) fn from_profile_with(
        profile: &ProfileConfig,
        env: impl Fn(&str) -> Option<String>,
    ) -> Option<Self> {
        Self::new(configured_keys(profile, env))
    }

    /// Number of configured key versions (for startup logging).
    pub fn key_versions(&self) -> Vec<u32> {
        self.keys.iter().map(|key| key.version).collect()
    }

    /// Sign with the newest non-retired key. `None` when every key is retired.
    pub fn sign(&self, input: &CallbackSignInput) -> Option<String> {
        self.sign_at(input, now_ms())
    }

    pub(crate) fn sign_at(&self, input: &CallbackSignInput, now: i64) -> Option<String> {
        let key = self.keys.iter().rev().find(|key| !key.retired)?;
        let nonce = input
            .nonce
            .clone()
            .filter(|nonce| !nonce.is_empty())
            .unwrap_or_else(random_nonce);
        let payload = CallbackPayload {
            r: input.run_id.clone(),
            s: input.scope.clone(),
            c: input.chat_id.clone(),
            o: input.operator_open_id.clone(),
            a: input.action.clone(),
            exp: now.saturating_add(input.ttl_ms),
            fp: input.policy_fingerprint.clone(),
            n: nonce,
            kv: key.version,
        };
        let encoded = base64url_encode(&serde_json::to_vec(&payload).ok()?);
        let signature = hmackey_base64url(&key.secret, &encoded)?;
        Some(format!("{CALLBACK_TOKEN_PREFIX}.{encoded}.{signature}"))
    }

    /// Verify a v1 token against the expected context.
    pub fn verify(
        &self,
        token: &str,
        expected: &CallbackExpected,
    ) -> Result<CallbackPayload, CallbackRejection> {
        self.verify_at(token, expected, now_ms())
    }

    pub(crate) fn verify_at(
        &self,
        token: &str,
        expected: &CallbackExpected,
        now: i64,
    ) -> Result<CallbackPayload, CallbackRejection> {
        let parts: Vec<&str> = token.split('.').collect();
        if parts.len() != 4 || format!("{}.{}", parts[0], parts[1]) != CALLBACK_TOKEN_PREFIX {
            return Err(CallbackRejection::Malformed);
        }
        let (encoded, signature) = (parts[2], parts[3]);
        if encoded.is_empty() || signature.is_empty() {
            return Err(CallbackRejection::Malformed);
        }

        let bytes = base64url_decode(encoded).ok_or(CallbackRejection::Malformed)?;
        let payload: CallbackPayload =
            serde_json::from_slice(&bytes).map_err(|_| CallbackRejection::Malformed)?;
        if payload.n.is_empty() {
            return Err(CallbackRejection::Malformed);
        }

        let key = self
            .keys
            .iter()
            .find(|key| key.version == payload.kv)
            .ok_or(CallbackRejection::UnknownKey)?;
        if !verify_hmac(&key.secret, encoded, signature) {
            return Err(CallbackRejection::BadSignature);
        }
        if payload.exp <= now {
            return Err(CallbackRejection::Expired);
        }
        if !matches_expected(&payload, expected) {
            return Err(CallbackRejection::ContextMismatch);
        }

        let mut nonces = lock_nonces(&self.nonces);
        nonces.retain(|_, expiry| *expiry > now);
        if nonces.contains_key(&payload.n) {
            return Err(CallbackRejection::Replay);
        }
        nonces.insert(payload.n.clone(), payload.exp);
        Ok(payload)
    }
}

/// Resolve the configured key list. Precedence: `extra.callback.keys`, then
/// `extra.callback.secret`/`extra.callbackSecret`, then the environment.
fn configured_keys(
    profile: &ProfileConfig,
    env: impl Fn(&str) -> Option<String>,
) -> Vec<CallbackKey> {
    if let Some(callback) = profile.extra.get("callback") {
        if let Some(keys) = callback_keys_from(callback.get("keys")) {
            return keys;
        }
        if let Some(secret) = non_empty_string(callback.get("secret")) {
            return vec![CallbackKey {
                version: 1,
                secret,
                retired: false,
            }];
        }
    }
    if let Some(keys) = callback_keys_from(profile.extra.get("callbackKeys")) {
        return keys;
    }
    if let Some(secret) = non_empty_string(profile.extra.get("callbackSecret")) {
        return vec![CallbackKey {
            version: 1,
            secret,
            retired: false,
        }];
    }
    for name in [CALLBACK_SECRET_ENV, LEGACY_CALLBACK_SECRET_ENV] {
        if let Some(secret) = env(name).and_then(|value| trimmed(value)) {
            return vec![CallbackKey {
                version: 1,
                secret,
                retired: false,
            }];
        }
    }
    Vec::new()
}

/// Parse `[{"version": 1, "secret": "…", "retired": false}]`. Returns `None`
/// when nothing valid is present so the caller can fall through to the next
/// source.
fn callback_keys_from(value: Option<&Value>) -> Option<Vec<CallbackKey>> {
    let entries = value?.as_array()?;
    let mut keys = Vec::new();
    for entry in entries {
        let Some(object) = entry.as_object() else {
            continue;
        };
        let Some(secret) = non_empty_string(object.get("secret")) else {
            continue;
        };
        let version = object
            .get("version")
            .and_then(Value::as_u64)
            .filter(|version| *version > 0 && *version <= u64::from(u32::MAX))
            .unwrap_or(1) as u32;
        let retired = object
            .get("retired")
            .and_then(Value::as_bool)
            .unwrap_or(false);
        keys.push(CallbackKey {
            version,
            secret,
            retired,
        });
    }
    if keys.is_empty() { None } else { Some(keys) }
}

fn non_empty_string(value: Option<&Value>) -> Option<String> {
    value
        .and_then(Value::as_str)
        .and_then(|value| trimmed(value.to_string()))
}

fn trimmed(value: String) -> Option<String> {
    let value = value.trim();
    if value.is_empty() {
        None
    } else {
        Some(value.to_string())
    }
}

fn matches_expected(payload: &CallbackPayload, expected: &CallbackExpected) -> bool {
    let run_id_matches = expected
        .run_id
        .as_deref()
        .map(|run_id| payload.r == run_id)
        .unwrap_or(true);
    let fingerprint_matches = expected
        .policy_fingerprint
        .as_deref()
        .map(|fingerprint| payload.fp == fingerprint)
        .unwrap_or(true);
    run_id_matches
        && fingerprint_matches
        && payload.s == expected.scope
        && payload.c == expected.chat_id
        && payload.o == expected.operator_open_id
        && payload.a == expected.action
}

fn lock_nonces(nonces: &Mutex<HashMap<String, i64>>) -> MutexGuard<'_, HashMap<String, i64>> {
    nonces
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

fn hmackey_base64url(secret: &str, message: &str) -> Option<String> {
    let mut mac = HmacSha256::new_from_slice(secret.as_bytes()).ok()?;
    mac.update(message.as_bytes());
    Some(base64url_encode(&mac.finalize().into_bytes()))
}

fn verify_hmac(secret: &str, message: &str, provided: &str) -> bool {
    let Some(signature) = base64url_decode(provided) else {
        return false;
    };
    let Ok(mut mac) = HmacSha256::new_from_slice(secret.as_bytes()) else {
        return false;
    };
    mac.update(message.as_bytes());
    // `verify_slice` is constant time and rejects a wrong length.
    mac.verify_slice(&signature).is_ok()
}

fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_millis() as i64)
        .unwrap_or(0)
}

fn random_nonce() -> String {
    let mut bytes = [0u8; 16];
    if getrandom::fill(&mut bytes).is_err() {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or(0);
        bytes.copy_from_slice(&nanos.to_le_bytes());
    }
    base64url_encode(&bytes)
}

// ---------------------------------------------------------------------------
// base64url (RFC 4648 §5, no padding)
// ---------------------------------------------------------------------------

const BASE64URL_ALPHABET: &[u8; 64] =
    b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

fn base64url_encode(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let first = u32::from(chunk[0]);
        let second = u32::from(chunk.get(1).copied().unwrap_or(0));
        let third = u32::from(chunk.get(2).copied().unwrap_or(0));
        let block = (first << 16) | (second << 8) | third;
        out.push(BASE64URL_ALPHABET[(block >> 18) as usize & 0x3f] as char);
        out.push(BASE64URL_ALPHABET[(block >> 12) as usize & 0x3f] as char);
        if chunk.len() > 1 {
            out.push(BASE64URL_ALPHABET[(block >> 6) as usize & 0x3f] as char);
        }
        if chunk.len() > 2 {
            out.push(BASE64URL_ALPHABET[block as usize & 0x3f] as char);
        }
    }
    out
}

fn base64url_decode(value: &str) -> Option<Vec<u8>> {
    // A base64 quantum is 4 characters; a remainder of 1 is impossible.
    if value.len() % 4 == 1 {
        return None;
    }
    let mut out = Vec::with_capacity(value.len() * 3 / 4);
    let mut buffer: u32 = 0;
    let mut bits: u32 = 0;
    for byte in value.bytes() {
        let digit = match byte {
            b'A'..=b'Z' => byte - b'A',
            b'a'..=b'z' => byte - b'a' + 26,
            b'0'..=b'9' => byte - b'0' + 52,
            b'-' => 62,
            b'_' => 63,
            // Padding and the standard alphabet are not part of the contract.
            _ => return None,
        } as u32;
        buffer = (buffer << 6) | digit;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buffer >> bits) as u8);
            buffer &= (1u32 << bits).wrapping_sub(1);
        }
    }
    // Non-zero leftover bits would not round-trip: reject non-canonical input.
    if bits > 0 && buffer != 0 {
        return None;
    }
    Some(out)
}

